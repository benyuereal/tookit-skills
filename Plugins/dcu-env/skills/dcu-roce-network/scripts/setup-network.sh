#!/bin/bash
# setup-network.sh — 节点静态 IP + MTU 9000 配置（RoCE 网络）
#
# 用途：在 RoCE v2 集群中为某节点的 NDR 网卡配置静态 IP（/27）与 MTU 9000。
#       每个节点 8 个网口（p66p1/p66p2/p61p1/p61p2/p82p1/p82p2/p72p1/p72p2），
#       各自落在 124.254.0.0/24 内的 8 个 /27 子网，网口号相同者同子网。
#
# 用法：
#   1. 确认本节点实际网口名（ip -br link 查看 NDR 网卡物理接口名，勿照抄 p66p1 等）
#   2. 传入节点号参数 1~4（决定每个 /27 子网内的偏移 IP，见下方 case）：bash setup-network.sh 2
#   3. 修改各分支 IP_MAP 使其与本节点实际网名一一对应（不可照抄）
#   4. chmod +x 后执行；如需开机自启见 SKILL.md「systemd 自启」
#
# 子网划分（8 个 /27，网关 124.254.0.254/24）：
#   p66p1: 124.254.0.1/27   p66p2: 124.254.0.33/27
#   p61p1: 124.254.0.65/27  p61p2: 124.254.0.97/27
#   p82p1: 124.254.0.129/27 p82p2: 124.254.0.161/27
#   p72p1: 124.254.0.193/27 p72p2: 124.254.0.225/27
# 每子网内 node1~4 依次取 .1~.4 偏移（如 p66p1 子网: node1=.1, node2=.2, ...）。
#   ⚠️ 每个子网是独立的 /27 网络，node1~4 的地址须严格一一对应（见 SKILL.md 踩坑）。
#     以下 case 直接固化了文档给出的 node1~4 绝对 IP 表。

set -euo pipefail

# 节点号（1~4），决定每 /27 子网内的偏移地址
NODE="${1:-1}"

# 网口 -> IP 映射（文档给出的 node1~4 绝对 IP 表，按 NODE 取值）
case "$NODE" in
  1)
    IP_MAP=(
      "p66p1 124.254.0.1/27"
      "p66p2 124.254.0.33/27"
      "p61p1 124.254.0.65/27"
      "p61p2 124.254.0.97/27"
      "p82p1 124.254.0.129/27"
      "p82p2 124.254.0.161/27"
      "p72p1 124.254.0.193/27"
      "p72p2 124.254.0.225/27"
    )
    ;;
  2)
    IP_MAP=(
      "p66p1 124.254.0.2/27"
      "p66p2 124.254.0.34/27"
      "p61p1 124.254.0.66/27"
      "p61p2 124.254.0.98/27"
      "p82p1 124.254.0.130/27"
      "p82p2 124.254.0.162/27"
      "p72p1 124.254.0.194/27"
      "p72p2 124.254.0.226/27"
    )
    ;;
  3)
    IP_MAP=(
      "p66p1 124.254.0.3/27"
      "p66p2 124.254.0.35/27"
      "p61p1 124.254.0.67/27"
      "p61p2 124.254.0.99/27"
      "p82p1 124.254.0.131/27"
      "p82p2 124.254.0.163/27"
      "p72p1 124.254.0.195/27"
      "p72p2 124.254.0.227/27"
    )
    ;;
  4)
    IP_MAP=(
      "p66p1 124.254.0.4/27"
      "p66p2 124.254.0.36/27"
      "p61p1 124.254.0.68/27"
      "p61p2 124.254.0.100/27"
      "p82p1 124.254.0.132/27"
      "p82p2 124.254.0.164/27"
      "p72p1 124.254.0.196/27"
      "p72p2 124.254.0.228/27"
    )
    ;;
  *)
    echo "错误: NODE 必须是 1~4（当前: $NODE）" >&2
    exit 1
    ;;
esac

# ⚠️ 若本节点实际接口名与上面不同，请改写 IP_MAP（务必 IP 与 MAC/网口一一对应，见 SKILL.md 踩坑）
for entry in "${IP_MAP[@]}"; do
  dev=$(echo "$entry" | cut -d' ' -f1)
  ip=$(echo "$entry" | cut -d' ' -f2)

  # 跳过不存在的网口（避免误配）
  if [ ! -d "/sys/class/net/$dev" ]; then
    echo "警告: 网口 $dev 不存在，跳过" >&2
    continue
  fi

  ip addr flush dev "$dev"
  ip addr add "$ip" dev "$dev"
  ip link set dev "$dev" mtu 9000
  ip link set dev "$dev" up
  echo "[OK] $dev -> $ip (mtu 9000)"
done

echo "配置完成（node$NODE）。验证: ip addr show dev <任一同子网网口>（应见 IP 且 mtu 9000）"
