#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""fmla_patch —— 给 FlashMLA-das 打 d=512 支持补丁。

## 为什么要有这个脚本（不是为了省事）

2026-11-25 踩了两次：

  ① **改错了文件**：一直在改 `dense_decode_hip.h`，而它是 hipify 自动
     生成的（文件第一行就写着）。setup.py 编的是 api.cpp，
     include 的是不带 `_hip` 的 `dense_decode.h`。
     也就是说：**改了一整天，编译器从来没读过那个文件。**
     每次"改动消失"都是 hipify 重新生成覆盖了它。
  ② 改了 `csrc/extension/flash_fwd_mla_kernel_fp8.h` 但没同步 `_hip.h`
     （hipify 产物），编译用的是 `_hip.h`，等于没改

**凡是「手工编辑 → 编译 → 发现没生效」的循环，都应该变成幂等脚本。**
这样至少能一行命令确认「补丁在不在」。

## 用法

    python3 -I scripts/fmla_patch.py --check     # 只检查，不修改（退出码 0=全在）
    python3 -I scripts/fmla_patch.py --apply     # 打补丁（幂等）
    python3 -I scripts/fmla_patch.py --selftest
"""
import argparse
import pathlib
import sys

REPO = pathlib.Path("/workspace/FlashMLA-das")

# **绝对不能直接改的文件**：这些是 hipify 自动生成的，第一行就写着
# "automatically generated by hipify"。改了会在下次 hipify 时被覆盖，
# 而且 setup.py 编的是 api.cpp（include 不带 _hip 的原始头文件），
# 所以你改的这半天根本没进过编译器。
# 2026-11-25 我在这里栽了整整一天。
DERIVED_SUFFIX = "_hip.h"

# (文件, 锚点, 替换成, 说明)
PATCHES = [
    (
        "csrc/api/dense_decode.h",
        "    if ((num_heads_q < 64 && num_heads_k == 1) || num_heads_k > 1 || arch.is_gfx928()) {\n"
        "        params.tile_scheduler_metadata_ptr = (DecodingSchedMeta*)tile_scheduler_metadata->data_ptr();\n"
        "        params.num_sm_parts = num_sm_parts;\n"
        "        params.num_splits_ptr = num_splits->data_ptr<int>();",

        "    // **这两个字段两个分支都必须赋值**（D14）。\n"
        "    // fp8 主 kernel 第一件事就解引用 tile_scheduler_metadata_ptr\n"
        "    // （flash_fwd_mla_kernel_fp8_hip.h:2615），而原来只在 if 分支赋值。\n"
        "    // H >= 64 走 else → 指针是残留值 → VMFault，报错无任何指向性。\n"
        "    params.tile_scheduler_metadata_ptr = (DecodingSchedMeta*)tile_scheduler_metadata->data_ptr();\n"
        "    params.num_sm_parts = num_sm_parts;\n"
        "    params.num_splits_ptr = num_splits->data_ptr<int>();\n"
        "    if ((num_heads_q < 64 && num_heads_k == 1) || num_heads_k > 1 || arch.is_gfx928()) {",
        "未初始化指针（H>=64 崩溃的根因）",
    ),
    (
        # 注意：这里把「旧锚点」写成永远不会匹配的占位，
        # 是因为这个补丁**已经手工打过且格式变了**（带逗号+续行）。
        # 保留一条记录，让 --check 仍能确认「512 没被回退」。
        "csrc/extension/flash_fwd_mla_kernel_fp8.h",
        "____never_matches____",
        "    static_assert(Headdim == 576 || Headdim == 512,\n"
        '                  "只实例化过 576（DSA/V4.1）与 512（GLM-5.3）");',
        "放开 d=512（GLM-5.3）",
    ),
]


def _p(path):
    return REPO / path


def check(emit=print):
    """检查补丁是否都在。**锚点变了也要报 False** —— 不能静默通过。"""
    ok = True
    for f, old, new, desc in PATCHES:
        if f.endswith(DERIVED_SUFFIX):
            emit("✗ %s 目标是 hipify 生成物（%s）—— 必须改原始 .h" % (desc, f))
            ok = False
            continue
        p = _p(f)
        if not p.is_file():
            emit("✗ 缺文件 %s" % f)
            ok = False
            continue
        s = p.read_text(encoding="utf-8")
        # **顺序很重要**：old 还在就一定是没打，不能被后面的启发式覆盖。
        # 2026-11-25 这里的顺序写反了，导致 _already_applied 误报通过，
        # 脚本说"补丁在"而文件里其实是原样 —— 白等一轮编译。
        if old in s:
            emit("✗ %s —— 未打（锚点还在）" % desc)
            ok = False
        elif new in s:
            emit("✓ %s" % desc)
        elif _already_applied(s, new):
            emit("✓ %s（已应用，格式与记录略有差异）" % desc)
        else:
            emit("? %s —— 锚点已变，需人工确认" % desc)
            ok = False
    return ok


def _already_applied(s, new):
    """补丁是否已打。

    判据是「新文本的关键行在不在」，不是「新文本整体在不在」——
    因为 new 里常常包含 old 的原文（我们是在前面插几行），
    打了补丁之后 `new in s` 成立，但更常见的失败是有人在 new 上
    又改了一行（比如调了注释），此时整体匹配失败但补丁实际上在。

    这里退一步：取 new 里最长的那行代码（去掉注释），
    它出现在文件里就算打过了。**这条判据对「锚点消失」和
    「从未打过」仍能区分** —— 后者 old 一定还在。
    """
    code = [ln.strip() for ln in new.splitlines()
            if ln.strip() and not ln.strip().startswith("//")]
    if not code:
        return False
    return max(code, key=len) in s


def _selftest_guard_order():
    """反向用例：old 还在时必须报 False，哪怕 new 的某行已存在。

    这是 2026-11-25 真实踩到的 bug —— 补丁把一行**本来就存在**的代码
    复制到 if 之前，于是「最长代码行在不在」永远为真，check 永远通过。
    """
    old = "    if (x) {\n        p = q;\n    }"
    new = "    p = q;\n    if (x) {\n        p = q;\n    }"
    # 未打补丁的文件里，p = q; 已存在（在 if 里面）
    s_unpatched = "void f() {\n" + old + "\n}\n"
    assert old in s_unpatched, "构造错误"
    assert not _already_applied.__doc__ or True
    # 关键断言：old 在的时候，不能被判成已应用
    applied = (new in s_unpatched) or (
        old not in s_unpatched and _already_applied(s_unpatched, new))
    assert not applied, "old 还在却被判成已应用 —— 这就是那个 bug"
    print("[ok] 反向：old 还在时不会误判为已应用")





def apply(emit=print):
    n = 0
    for f, old, new, desc in PATCHES:
        if f.endswith(DERIVED_SUFFIX):
            emit("拒绝：%s 目标是 hipify 生成物（%s）" % (desc, f))
            continue
        p = _p(f)
        if not p.is_file():
            emit("跳过（文件不存在）：%s" % f)
            continue
        s = p.read_text(encoding="utf-8")
        if old in s:
            p.write_text(s.replace(old, new, 1), encoding="utf-8")
            emit("已打补丁：%s" % desc)
            n += 1
        elif new in s:
            emit("已存在，跳过：%s" % desc)
        else:
            emit("⚠ 锚点不匹配，跳过：%s（%s）" % (desc, f))
    return n


def selftest():
    """不碰真仓库 —— 用临时目录验 check/apply 的幂等性。"""
    import tempfile
    global REPO
    saved = REPO
    try:
        with tempfile.TemporaryDirectory() as td:
            REPO = pathlib.Path(td)
            f, old, new, desc = PATCHES[1]
            fp = _p(f)
            fp.parent.mkdir(parents=True, exist_ok=True)
            fp.write_text("void f() {\n" + old + "\n}\n", encoding="utf-8")

            assert not check(emit=lambda *_: None), "未打补丁时 check 应为 False"
            print("[ok] 反向：未打补丁时 check 返回 False")

            assert apply(emit=lambda *_: None) == 1, "第一次 apply 应改 1 处"
            print("[ok] 正向：apply 生效")

            assert apply(emit=lambda *_: None) == 0, "幂等：第二次 apply 不应再改"
            print("[ok] 幂等：重复 apply 不改动")

            assert new in fp.read_text(encoding="utf-8"), "改动应落盘"
            print("[ok] 改动确实写入文件")

            fp.write_text("void f() { /* 完全不认识 */ }\n", encoding="utf-8")
            assert not check(emit=lambda *_: None), "锚点不匹配时 check 应为 False"
            print("[ok] 反向：锚点消失时 check 返回 False（不会静默通过）")

            _selftest_guard_order()

        print("\nselftest PASS（6 项，不碰真实仓库）")
        return 0
    finally:
        REPO = saved


def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--apply", action="store_true")
    g.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    if a.check:
        return 0 if check() else 1
    apply()
    return 0


if __name__ == "__main__":
    sys.exit(main())
